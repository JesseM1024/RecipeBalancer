    private final int width;
    private final int height;
    private final String[] rows;

    private PixelIcon(String... rows) {
        this.rows = rows;
        this.height = rows.length;
        int max = 0;
        for (String row : rows) {
            max = Math.max(max, row.length());
        }
        this.width = max;
    }

    public int width() {
        return width;
    }

    public int height() {
        return height;
    }

    /** 逐行合并连续像素成一个矩形，避免逐像素 fill 造成过多绘制批次。 */
    public void draw(GuiGraphics graphics, int x, int y, int color) {
        for (int row = 0; row < rows.length; row++) {
            String line = rows[row];
            int runStart = -1;
            for (int col = 0; col <= line.length(); col++) {
                boolean filled = col < line.length() && line.charAt(col) == '#';
                if (filled && runStart < 0) {
                    runStart = col;
                } else if (!filled && runStart >= 0) {
                    graphics.fill(x + runStart, y + row, x + col, y + row + 1, color);
                    runStart = -1;
                }
            }
        }
    }
